//               <cmath> ბიბლიოთეკის სრული კონსპექტი C++-ში
//           (აბრევიატურები, დანიშნულება, დატვირთვა და გამოყენება)
// 1. მოდული (აბსოლუტური მნიშვნელობა)

// abs(x)   -> ABSolute value
//   • რას აკეთებს: მთელ რიცხვს (int) ჩამოაშორებს უარყოფით ნიშანს და აბრუნებს დადებითს.
//   • რატომ ვიყენებთ: როცა გვაინტერესებს მანძილი, სხვაობა ან გადახრა ორი რიცხვის შედარებისას.
//   • მაგალითი: abs(-10) -> 10

// fabs(x)  -> Floating-point ABSolute value
//   • რას აკეთებს: ათწილად რიცხვს (double/float) ჩამოაშორებს უარყოფით ნიშანს.
//   • რატომ ვიყენებთ: ათწილადებში ცვლილების სიდიდისა თუ სხვაობის დასადგენად (მაგ. ტემპერატურა, ფასები).
//   • მაგალითი: fabs(-3.14) -> 3.14

// labs(x)  -> Long ABSolute value
//   • რას აკეთებს: იგივეა, რაც abs(x), მაგრამ გამოიყენება ძალიან დიდი მთელი რიცხვებისთვის (long int).
//   • მაგალითი: labs(-2000000000L) -> 2000000000



// 2. ხარისხი, ფესვი და ჰიპოტენუზა

// pow(x, y)-> POWer
//   • რას აკეთებს: x რიცხვი აჰყავს y ხარისხში (x^y).
//   • რატომ ვიყენებთ: ფართობის, მოცულობის, რთული პროცენტების ან მათემატიკური ფორმულების დასათვლელად.
//   • მაგალითი: pow(2, 3) -> 8.0

// sqrt(x)  -> Square RooT
//   • რას აკეთებს: იღებს კვადრატულ ფესვს x-იდან (√x).
//   • რატომ ვიყენებთ: გეომეტრიაში გვერდების დასადგენად, მანძილების ფორმულებში.
//   • მაგალითი: sqrt(25) -> 5.0 (შენიშვნა: უარყოფითზე ამოაგდებს NaN-ს).

// cbrt(x)  -> CuBe RooT
//   • რას აკეთებს: იღებს კუბურ ფესვს (∛x).
//   • რატომ ვიყენებთ: კუბის გვერდის მოსაძებნად; უპირატესობა: მუშაობს უარყოფით რიცხვებზეც!
//   • მაგალითი: cbrt(-27) -> -3.0

// hypot(x, y) -> HYPOTenuse
//   • რას აკეთებს: ითვლის მართკუთხა სამკუთხედის ჰიპოტენუზას: √(x² + y²).
//   • რატომ ვიყენებთ: საკოორდინატო სიბრტყეზე ორ წერტილს შორის მანძილის მარტივად დასათვლელად.
//   • მაგალითი: hypot(3, 4) -> 5.0



// 3. დამრგვალება (ძალიან მნიშვნელოვანია საგამოცდოდ!)

// floor(x) -> FLOOR ("იატაკი")
//   • რას აკეთებს: ამრგვალებს ყოველთვის ქვემოთ (ნაკლებობით, უახლოეს უმცირეს მთელ რიცხვამდე).
//   • რატომ ვიყენებთ: როცა გვინდა სრული რაოდენობის დათვლა (მაგ. რამდენი მთლიანი ნივთის ყიდვა შეგვიძლია).
//   • მაგალითი: floor(4.9) -> 4.0 | floor(-2.1) -> -3.0

// ceil(x)  -> CEILing ("ჭერი")
//   • რას აკეთებს: ამრგვალებს ყოველთვის ზემოთ (მეტობით, უახლოეს უდიდეს მთელ რიცხვამდე).
//   • რატომ ვიყენებთ: როცა გვინდა მინიმალური ტევადობის დათვლა (მაგ. რამდენი ყუთია საჭირო N ნივთისთვის).
//   • მაგალითი: ceil(4.1) -> 5.0 | ceil(-2.9) -> -2.0

// round(x) -> ROUND
//   • რას აკეთებს: სტანდარტული მათემატიკური დამრგვალება (.5 და მეტი მიდის ზემოთ, ნაკლები ქვემოთ).
//   • რატომ ვიყენებთ: საშუალო ქულების, ნიშნებისა და ფასების რეალური წესით დასამრგვალებლად.
//   • მაგალითი: round(4.5) -> 5.0 | round(4.4) -> 4.0

// trunc(x) -> TRUNCate ("ჩამოჭრა")
//   • რას აკეთებს: უბრალოდ აჭრის წილად ნაწილს (არ ამრგვალებს, უბრალოდ გადაყრის მძიმის შემდეგ ციფრებს).
//   • რატომ ვიყენებთ: როცა გვჭირდება მხოლოდ რიცხვის მთელი ნაწილის გამოყოფა.
//   • მაგალითი: trunc(4.9) -> 4.0 | trunc(-2.9) -> -2.0



// 4. ლოგარითმები და ექსპონენტა

// exp(x)   -> EXPonential
//   • რას აკეთებს: e რიცხვი (e ≈ 2.71828) აჰყავს x ხარისხში (e^x).
//   • რატომ ვიყენებთ: ფინანსურ მოდელებში, მოსახლეობის ზრდის ან ფიზიკური პროცესების დათვლისას.
//   • მაგალითი: exp(1) -> 2.71828

// log(x)   -> LOGarithm
//   • რას აკეთებს: ითვლის ნატურალურ ლოგარითმს (ln x, ფუძით e).
//   • რატომ ვიყენებთ: მათემატიკური და ფიზიკური ფორმულების ამოსახსნელად.
//   • მაგალითი: log(2.71828) -> 1.0

// log10(x) -> LOGarithm base 10
//   • რას აკეთებს: ითვლის ათობით ლოგარითმს (lg x, ფუძით 10).
//   • რატომ ვიყენებთ: რიცხვში ციფრების რაოდენობის საპოვნელად ან ხმის/მიწისძვრის მასშტაბების დასათვლელად.
//   • მაგალითი: log10(100) -> 2.0

// log2(x)  -> LOGarithm base 2
//   • რას აკეთებს: ითვლის ორობით ლოგარითმს (log₂ x).
//   • რატომ ვიყენებთ: ინფორმატიკაში, მონაცემთა სტრუქტურებსა და ალგორითმების სირთულის დასადგენად.
//   • მაგალითი: log2(16) -> 4.0



// 5. ტრიგონომეტრია (ყურადღება: კუთხე გადაეცემა მხოლოდ რადიანებში!)

// sin(x)   -> SINe
//   • რას აკეთებს: ითვლის x კუთხის სინუსს.
//   • რატომ ვიყენებთ: ტალღების, რხევების, გრაფიკისა და ფიზიკური ტრაექტორიის დასათვლელად.

// cos(x)   -> COSine
//   • რას აკეთებს: ითვლის x კუთხის კოსინუსს.
//   • რატომ ვიყენებთ: გრაფიკაში ვექტორების პროექციისთვის და კუთხეების გამოთვლისთვის.

// tan(x)   -> TANgent
//   • რას აკეთებს: ითვლის x კუთხის ტანგენსს.
//   • რატომ ვიყენებთ: დახრილობის კუთხის ან სიმაღლის საპოვნელად.

// asin(x), acos(x), atan(x) -> Arc SINe / Arc COSine / Arc TANgent
//   • რას აკეთებს: შებრუნებული ტრიგონომეტრიული ფუნქციებია (არკ-ფუნქციები).
//   • რატომ ვიყენებთ: გვერდების შეფარდებით კუთხის მნიშვნელობის საპოვნელად (აბრუნებს რადიანს).



// 6. სხვა გამოსადეგი ოპერაციები

// fmod(x, y)-> Floating-point MODulo
//   • რას აკეთებს: იპოვის ნაშთს ათწილადების გაყოფისას (x / y).
//   • რატომ ვიყენებთ: ჩვეულებრივი პროცენტის ოპერატორი (%) მუშაობს მხოლოდ მთელ რიცხვებზე (int).
//     ათწილადებზე ნაშთის საპოვნელად აუცილებელია fmod().
//   • მაგალითი: fmod(7.5, 2.1) -> 1.2



//ტიპების (int vs double) წესი <cmath>-ში

// 1. <cmath>-ის თითქმის ყველა ფუნქცია აბრუნებს double ტიპის მნიშვნელობას.
// 2. თუ ფუნქციას გადავცემთ int-ს, C++ მას ავტომატურად გადაიყვანს double-ში.
// 3. შედეგი ყოველთვის შეინახე double ტიპის ცვლადში, რომ სიზუსტე არ დაკარგო!
// 4. ერთადერთი გამონაკლისი: abs(x) გამოიყენება int-ისთვის, ხოლო fabs(x) double-ისთვის.



//N1: შემოდის ერთი მთელი რიცხვი. იპოვეთ მისი მოდული (აბსოლუტური მნიშვნელობა) და შედეგი გამობეჭდეთ;
