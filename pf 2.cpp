//N18 შემოდის კუთხე გრადუსებში. გამოითვალეთ ამ კუთხის სინუსი და შედეგი გამობეჭდეთ;
#include <iostream>
#include <cmath>
using namespace std;

int main() {
    double x, radians; // აქ შემოდის გრადუსი
    cin >> x;

    // გრადუსის გადაყვანა რადიანებში და სინუსის გამოთვლა
    radians = x * acos(-1) / 180.0;

    cout << "sin = " << sin(radians) << endl;
    
    return 0;
}

//N19 შემოდის ორი ათწილადი რიცხვი a და b. გამოითვალეთ გამოსახულების მნიშვნელობა: z = sqrt(abs(a - b)) + pow(a, b); და შედეგი გამობეჭდეთ;
#include <iostream>
#include <cmath>
using namespace std;
int main() {
    double a, b, z;
    cin >> a >> b;

    z = sqrt(abs(a - b)) + pow(a, b);
    cout << "z =" << z << endl;
    return 0;
}

