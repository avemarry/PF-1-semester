// ამოცანა #12: შემოდის ნივთის ფასი ათწილადებში. ცალ-ცალკე გამოყავით და გამობეჭდეთ ფასის მთელი ნაწილი (ლარები) და წილადი ნაწილი (თეთრები);

#include <iostream>  // სავალდებულო ბიბლიოთეკა სტანდარტული შეტანა/გამოტანის ოპერაციებისთვის (cin, cout)
#include <cmath>     // მათემატიკური ბიბლიოთეკა (<cmath>), რომელიც აუცილებელია ისეთი ფუნქციების გამოსაყენებლად, როგორიცაა trunc() და round()
using namespace std; // სტანდარტული სახელთა სივრცის გამოყენება, რომ კოდში არ დაგვჭირდეს std::-ის მუდმივად წერა

int main () 
{
    double x, lari;  // x და lari იქმნება double ტიპად:
                     // 1. x არის მთლიანი ფასი (მაგ: 12.50), რომელიც ათწილადია და აუცილებლად double სჭირდება.
                     // 2. lari არის მთელი ნაწილი, მაგრამ რადგან trunc() ფუნქცია შედეგს ყოველთვის double ფორმატში აბრუნებს (12.0), ტიპების თანხვედრისთვის lari-ც double-ია.
    
    int tetri;       // tetri იქმნება int (მთელრიცხოვან) ტიპად, რადგან თეთრები რეალურ ცხოვრებაში და გამოთვლებში მთელი რიცხვია (მაგალითად 50 თეთრი და არა 0.50).
    
    cin >> x;        // კლავიატურიდან იღებს მომხმარებლის მიერ შეყვანილ ათწილად ფასს და ინახავს x ცვლადში

    lari = trunc(x);                 // trunc() ფუნქცია აჭრის x-ის წილად ნაწილს (ტოვებს მხოლოდ ლარებს) და შედეგს ანიჭებს lari ცვლადს
    
    tetri = round ((x - lari) * 100);/* გამოთვლის ლოგიკა: მთლიან ფასს (x) აკლებს ლარებს (lari), რათა მიიღოს წილადი 
                                        ნაწილი (მაგ. 0.5). შემდეგ ამრავლებს 100-ზე და round() ფუნქციით ამრგვალებს, 
                                        რომ მიიღოს მკვეთრი მთელი რიცხვი (თეთრებში, მაგ. 50). შედეგი ინახება tetri ცვლადში. */

    cout << "ფასის მთელი ნაწილი, ლარებში: " << lari << " " << "ლარი" << endl; 
    // ეკრანზე გამოაქვს ტექსტი, უერთებს lari ცვლადის მნიშვნელობას, ამატებს სიტყვას "ლარი" და გადადის ახალ ხაზზე (endl)
    
    cout << "ფასის წილადი ნაწილი, თეთრებში: " << tetri << " " << "თეთრი" << endl; 
    // ეკრანზე გამოაქვს ტექსტი, უერთებს tetri ცვლადის მთელ მნიშვნელობას, ამატებს სიტყვას "თეთრი" და გადადის ახალ ხაზზე
    
    return 0;        // ასრულებს პროგრამის მუშაობას წარმატებით
}

